import AppKit
import ApplicationServices

/// Polls the general pasteboard (macOS has no change notification) and records new text.
@MainActor
final class ClipboardMonitor: NSObject {
    private let pasteboard = NSPasteboard.general
    private let history: ClipboardHistory
    private let settings: ClipboardSettings
    private var lastChangeCount: Int
    private var timer: Timer?

    /// Markers apps put on content that should not be kept (see nspasteboard.org).
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
    /// The marker password managers put on passwords.
    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")

    init(history: ClipboardHistory, settings: ClipboardSettings) {
        self.history = history
        self.settings = settings
        self.lastChangeCount = NSPasteboard.general.changeCount
        super.init()
    }

    func start() {
        capture()
        let timer = Timer(timeInterval: 0.4, target: self, selector: #selector(poll), userInfo: nil, repeats: true)
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Writes text to the pasteboard without recording it as a new entry.
    func write(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    @objc private func poll() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        capture()
    }

    /// Prefers the source the copying app declares (nspasteboard.org), else the frontmost app,
    /// which is almost always the one that just copied.
    private func sourceBundleID() -> String? {
        if let declared = pasteboard.string(forType: .init("org.nspasteboard.source")), !declared.isEmpty {
            return declared
        }
        return NSWorkspace.shared.frontmostApplication?.bundleIdentifier
    }

    private func capture() {
        let types = pasteboard.types ?? []
        if types.contains(where: Self.ignoredTypes.contains) {
            return
        }
        if settings.ignorePasswords, types.contains(Self.concealedType) || focusIsInPasswordField() {
            return
        }
        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return }
        history.add(text, sourceBundleID: sourceBundleID(), removingDuplicates: settings.removeDuplicates)
    }

    /// Whether the focused control in the frontmost app is a password field. Standard
    /// password fields refuse to copy, but custom ones may not, so check at copy time.
    /// Uses the Accessibility permission; without it this is always false.
    private func focusIsInPasswordField() -> Bool {
        let system = AXUIElementCreateSystemWide()
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, "AXFocusedUIElement" as CFString, &focused) == .success,
              let focused, CFGetTypeID(focused) == AXUIElementGetTypeID()
        else { return false }
        var subrole: CFTypeRef?
        AXUIElementCopyAttributeValue(focused as! AXUIElement, "AXSubrole" as CFString, &subrole)
        return subrole as? String == "AXSecureTextField"
    }
}
